import type { ReactNode } from 'react';

/**
 * 진료 4대 축의 작은 아이콘.
 *
 * ★★ 왜 그린 SVG 인가 (2026-08-28) ★★
 *   오너 요청은 "GPT API 로 어울리는 이모티콘" 이었는데, 아이콘에는 그린 선이 맞다 —
 *     · 어두운 유리 카드 위라 **배경이 없어야** 한다. 생성 이미지는 배경 처리가 지저분하다.
 *     · 선 색이 currentColor 라 카드 색이 바뀌면 같이 따라온다.
 *     · **선이 그려지는 연출**은 벡터에서만 된다(래스터로는 불가능).
 *     · 넷 다 같은 굵기·같은 결로 맞출 수 있다. 생성 이미지는 매번 결이 달라진다.
 *   ⚠️ 생성 이미지로 바꾸려면 배경 투명 + 넷의 결 통일을 먼저 풀 것.
 *
 * ★ 24×24 격자에 그리고 **64px** 로 띄운다. 26px → 42px → 64px 로 두 번 키웠다.
 *   오너가 두 번 다 "안 보인다 / 더 크게" 라고 했다 — 카드가 300px 인데 42px 은 작다.
 * ★ 선 굵기는 크기에 반비례로 줄인다(1.5 → 1.1). 안 줄이면 굵기가 그대로 커져
 *   손으로 그린 결이 아니라 굵은 도형으로 보인다.
 * ★ 끝은 둥글게. 진료 이름이 이미 글자로 있으므로 아이콘은
 *   **읽는 것이 아니라 알아보는 것**이다 — 자세히 그리지 않는다.
 * ⚠️ aria-hidden 이다. 아이콘이 뜻을 지고 있지 않으므로 스크린리더가 읽을 것이 없다.
 * ⚠️ .icon-draw 는 손을 올리면 선이 다시 그려지는 연출이다(globals.css).
 *    stroke-dasharray 를 쓰므로 fill 을 넣지 말 것 — 채우면 그려지는 것이 안 보인다.
 * ⚠️ 모든 path 에 pathLength={1} 이 있어야 한다. 없으면 dasharray 고정값이 실제 선 길이와
 *    안 맞아 애니메이션 대부분이 빈 시간이 된다(그래서 처음에 티가 안 났다).
 */
/*
 * ⚠️⚠️ box 는 **그림에 딱 맞는 상자**여야 한다 (2026-08-31) ⚠️⚠️
 *   넷 다 24×24 격자를 공유하고 있었는데, 실제 그림은 그 안에서 가운데 60% 만 썼다.
 *   그래서 64px 로 키워도 화면에서는 여전히 작아 보였다(오너: "잘 안 그려진다").
 *   아이콘마다 자기 그림에 맞춘 상자를 주면 같은 64px 안에서 그림이 꽉 찬다.
 * ⚠️ 상자는 **정사각**으로 둘 것. 가로세로 비가 다르면 선 굵기가 한쪽으로 늘어난다.
 */
function Svg({ children, box, size = 64 }: { children: ReactNode; box: string; size?: number }) {
  return (
    <svg
      className="icon-draw"
      width={size}
      height={size}
      viewBox={box}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.1"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      focusable="false"
    >
      {children}
    </svg>
  );
}

